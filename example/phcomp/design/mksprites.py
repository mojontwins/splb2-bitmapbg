#!/usr/bin/env python3
"""One-off: the compilation's sprite sheet (gfx/sprites.png): 16x16
frames, 16 a row, white = ink (conv.py makes the masks). Sources: pheng's
sprites.png, the originals' UDGs, a few drawn here."""
from PIL import Image
OUT = '/home/claude/work/splib2-bitmapbg/example/phcomp/gfx/sprites.png'
ph = Image.open('/home/claude/work/phc/in/zip/brujas/gfx/sprites.png').convert('RGB')
frames = []      # list of (name, 16 rows of 16-bit ints)
def from_ph(cx, cy):
    px = ph.load()
    return [sum(0x8000 >> x for x in range(16) if px[cx*16+x, cy*16+y] != (0, 0, 0)) for y in range(16)]
def from_udg(game, combo):
    m = open('/home/claude/work/phc/orig/%s.mem' % game, 'rb').read()
    rows = [0] * 16
    for k, ch in enumerate(combo):
        base = 0xFF58 + (ord(ch) - 65) * 8
        for y in range(8):
            rows[(k // 2) * 8 + y] |= m[base + y] << (8 if k % 2 == 0 else 0)
    return rows
def mirror(rows):
    return [int('{:016b}'.format(r)[::-1], 2) for r in rows]
def art(s):
    rows = s.split()
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), rows
    return [sum(0x8000 >> x for x in range(16) if r[x] == '#') for r in rows]
def add(name, rows):
    frames.append((name, rows))
def add4(name, a, b, mirrored=True):
    """left f0, left f1, right f0, right f1 (a, b face left)"""
    add(name + '_l0', a); add(name + '_l1', b)
    add(name + '_r0', mirror(a) if mirrored else a); add(name + '_r1', mirror(b) if mirrored else b)
# 0-7 Phantomas (pheng): left walk 0 1 2, left jump, right walk 4 5 6, right jump
for i in range(8): add('ph%d' % i, from_ph(i, 0))
# 8 devil (pheng 8-11), 12 knight (pheng 12-15), 16 bubble, 20 blob
for i in range(8, 16): add('ph%d' % i, from_ph(i, 0))
for i in range(8): add('ph1_%d' % i, from_ph(i, 1))
# 24 witch (Brujas MNOP / QRST face right in the original)
w0 = from_udg('brujas', 'MNOP'); w1 = from_udg('brujas', 'QRST')
add4('witch', mirror(w0), mirror(w1))
# 28 alien (Luna MNOP / QRST)
add4('alien', from_udg('luna', 'MNOP'), from_udg('luna', 'QRST'), False)
# 32 astronaut (Luna: GHIJ GHKL run left, ABCD ABEF right)
add('astro_l0', from_udg('luna', 'GHIJ')); add('astro_l1', from_udg('luna', 'GHKL'))
add('astro_r0', from_udg('luna', 'ABCD')); add('astro_r1', from_udg('luna', 'ABEF'))
# 36 android (Infinito 3: GHIJ GHKL / ABCD ABEF)
add('andr_l0', from_udg('inf3', 'ABCD')); add('andr_l1', from_udg('inf3', 'ABEF'))
add('andr_r0', from_udg('inf3', 'GHIJ')); add('andr_r1', from_udg('inf3', 'GHKL'))
# 40 policeman (V v1's figure)
c0 = art('''.....#####...... ....#######..... ...#########.... ......#..#...... .....######..... .....#.##.#..... ......####...... ....########.... ...##.####.##... ..##..####..##.. ..#...####...##. ......####...... ......#..#...... .....##..##..... .....#....#..... ....##....##....''')
c1 = art('''.....#####...... ....#######..... ...#########.... ......#..#...... .....######..... .....#.##.#..... ......####...... ....########.... ...##.####.##... ..##..####..#... .##...####...... ......####...... ......#..#...... ......#..##..... .....##...#..... .....#....##....''')
add4('cop', c0, c1)
# 44 drop: falling drop x2, splash x2
add('drop0', art('''................ ................ .......##....... ......####...... ......####...... .....######..... .....######..... .....######..... ......####...... .......##....... ................ ................ ................ ................ ................ ................'''))
add('drop1', art('''................ ................ ................ .......##....... .......##....... ......####...... .....######..... .....######..... .....######..... ......####...... .......##....... ................ ................ ................ ................ ................'''))
add('splash0', art('''................ ................ ................ ................ ................ ................ ................ ................ ................ ................ ..#.........#... ...#..#..#.#.... ....#.#..#.#.... .#..#......#..#. ..##........##.. ................'''))
add('splash1', art('''................ ................ ................ ................ ................ ................ ................ ................ #..............# .#....#..#....#. ................ ..#..........#.. ................ ................ ................ ................'''))
# 48 bird (white bird of V): 2 frames + mirrored
b0 = art('''................ ................ ..........###... .........#####.. ........##.#.### ........######.. ..##...######... .####.#######... ..###########... ...#########.... ....#######..... .....#####...... ......#..#...... .....##.##...... ................ ................''')
b1 = art('''................ ..##............ ..###......###.. ...###....#####. ....###..##.#.## .....##.######.. ......#######... .....########... ....#########... ...#########.... ....#######..... .....#####...... ......#..#...... .....##.##...... ................ ................''')
add4('bird', mirror(b0), mirror(b1))
# 52 broom (the witches' broom, an item): 2 frames
br = art('''................ ................ ................ ................ ................ ................ .##............. ####............ #####........... ###############. #####........... ####............ .##............. ................ ................ ................''')
br1 = art('''................ ................ ................ ................ ................ .#.............. ###............. ####............ #####........... ###############. #####........... ####............ ###............. .#.............. ................ ................''')
add4('broom', br, br1)
# 56 ball (bouncing ball / cherry)
ba = art('''................ ................ .....######..... ....##....##.... ...##.##...##... ...#.###....#... ...#..#.....#... ...#.........#.. ...#.........#.. ...##.......##.. ....##.....##... .....#######.... ................ ................ ................ ................''')
add4('ball', ba, mirror(ba), False)
# 60 hopper (a green thing that hops, V)
h0 = art('''................ ................ ................ ......####...... ....########.... ...##########... ..###.##.#####.. ..############.. ..#.########.#.. ..############.. ...##########... ....########.... ....##....##.... ...###....###... ................ ................''')
h1 = art('''................ ................ ......####...... ....########.... ...##########... ..###.##.#####.. ..############.. ..#.########.#.. ..############.. ...##########... ....########.... ...#........#... ..##........##.. ................ ................ ................''')
add4('hopper', h0, h1)
# 64 bat
t0 = art('''................ ................ ................ ##............## ###....##....### .####.####.####. ..############.. ...###.##.###... ....########.... .....######..... ......#..#...... ................ ................ ................ ................ ................''')
t1 = art('''................ ................ ................ ................ ................ .......##....... ..###.####.###.. .##############. ####.######.#### ###...####...### ##.....##.....## #......#.......# ................ ................ ................ ................''')
add4('bat', t0, t1, False)
# 68 rocket (Luna's goal), computer (Infinito's goal), fireball x2
add('rocket', art('''.......##....... ......####...... ......####...... .....##..##..... .....#.##.#..... .....##..##..... .....######..... .....######..... .....######..... ....########.... ...##.####.##... ..###.####.###.. ..##..#..#..##.. ......#..#...... .....#.##.#..... ....#..##..#....'''))
add('computer', art('''################ #..............# #.############.# #.#..........#.# #.#.##..##.#.#.# #.#..........#.# #.#.#####..#.#.# #.############.# #..............# ################ #.#.#.#..#.#.#.# ################ #..##..##..##..# #..##..##..##..# ################ ................'''))
fb = art('''................ ................ ................ ................ ......####...... ....##.##.##.... ...#.######.#... ...##########... ...##########... ...#.######.#... ....##.##.##.... ......####...... ................ ................ ................ ................''')
add('fire0', fb); add('fire1', mirror([r << 0 for r in fb[::-1]]))
# 72 platform (moving, 16x8 on top), 2 frames alike
pl = art('''################ #.##.##.##.##.## ################ .#............#. ................ ................ ................ ................ ................ ................ ................ ................ ................ ................ ................ ................''')
add('plat0', pl); add('plat1', pl)
# 74 heart (life), key
add('heart', art('''................ ................ ...###...###.... ..#####.#####... .############... .############... .############... ..##########.... ...########..... ....######...... .....####....... ......##........ ................ ................ ................ ................'''))
add('key', art('''................ ................ ................ ..####.......... .#....#......... #..##..######### #..##..#..#.#.## .#....#......... ..####.......... ................ ................ ................ ................ ................ ................ ................'''))
print(len(frames), 'frames')
for i, (n, r) in enumerate(frames):
    print(i, n, end='; ')
print()
H = ((len(frames) + 15) // 16) * 16
im = Image.new('RGB', (256, H))
px = im.load()
for i, (n, rows) in enumerate(frames):
    for y in range(16):
        for x in range(16):
            if rows[y] & (0x8000 >> x):
                px[(i % 16) * 16 + x, (i // 16) * 16 + y] = (255, 255, 255)
im.save(OUT)
im.resize((256 * 3, H * 3), Image.NEAREST).save('/home/claude/work/phc/look/sprites3.png')
open('/home/claude/work/splib2-bitmapbg/example/phcomp/design/spritenames.txt', 'w').write(''.join('%d %s\n' % (i, n) for i, (n, r) in enumerate(frames)))
