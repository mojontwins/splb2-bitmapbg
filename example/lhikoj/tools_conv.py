#!/usr/bin/env python3
"""Asset converter for the Lhikoj C port.
Reads the original ZX Basic sources/binaries and writes src/assets.h
(z88dk #asm data blocks)."""
import re, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
BAS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'orig')
GFX = os.path.join(HERE, 'gfx')

def read_array(path, name):
    s = open(path, 'rb').read().decode('latin-1')
    i = s.index('Dim ' + name); j = s.index('{', i); k = s.index('}', j)
    return [int(x) for x in re.findall(r'-?\d+', s[j:k])]

def asm_bytes(data, per=16):
    out = []
    for i in range(0, len(data), per):
        out.append('\tdefb ' + ','.join(str(b & 255) for b in data[i:i+per]))
    return '\n'.join(out)

sprset = read_array(os.path.join(BAS, 'lhikojSpriteSet.bas'), 'lhikojSpriteSet')
charset = read_array(os.path.join(BAS, 'lhikojCharSet.bas'), 'lhikojCharSet')

# ---------------------------------------------------------------- sprites
def sprite16(c):
    """chars c..c+3 = TL,TR,BL,BR -> 16 rows of 16-bit ints"""
    rows = []
    for half in (0, 2):
        for y in range(8):
            rows.append((sprset[(c+half)*8+y] << 8) | sprset[(c+half+1)*8+y])
    return rows

def make_mask(rows):
    ink = [[(rows[y] >> (15-x)) & 1 for x in range(16)] for y in range(16)]
    # outside = background pixels reachable from the border
    out = [[0]*16 for _ in range(16)]
    st = [(x, y) for x in range(16) for y in (0, 15)] + [(x, y) for y in range(16) for x in (0, 15)]
    while st:
        x, y = st.pop()
        if 0 <= x < 16 and 0 <= y < 16 and not out[y][x] and not ink[y][x]:
            out[y][x] = 1
            st += [(x+1, y), (x-1, y), (x, y+1), (x, y-1)]
    m = []
    for y in range(16):
        v = 0
        for x in range(16):
            keep = out[y][x]
            # 1px halo around the ink so the sprite reads on patterned fills
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    xx, yy = x+dx, y+dy
                    if 0 <= xx < 16 and 0 <= yy < 16 and ink[yy][xx]:
                        keep = 0
            v = (v << 1) | keep
        m.append(v)
    return m

frames = []
for f in (0, 16, 32, 48):           # down, up, right, left
    for k in range(3):
        frames.append(f + 4*k)
for base in (64, 80):               # ice game: normal / upside-down guy
    for facing in (0, 8):
        for step in (0, 4):
            frames.append(base + facing + step)

BL = [0, 255]
spr = BL * 8                        # top padding for the very first column
for c in frames:
    g = sprite16(c); m = make_mask(g)
    for col in (0, 1):
        sh = 8 if col == 0 else 0
        for y in range(16):
            spr += [(g[y] >> sh) & 255, (m[y] >> sh) & 255]
        spr += BL * 8
FRAME = 96                          # 3rd column -> SPNullSprPtr at runtime
assert len(spr) == 16 + FRAME*len(frames)

# ---------------------------------------------------------------- vectors
screens = ['001-P1', '001-P2', '001-P3', '001-P4', '002-P1', '002-P2',
           '002-P3', '002-P4', '002-P5', '000-P0', 'scrolly']

# ---------------------------------------------------------------- ice levels
ice_src = open(os.path.join(BAS, 'iceLevels.bas'), 'rb').read().decode('latin-1')
ice_levels = []
for n in range(4):
    i = ice_src.index('iceLevel%d:' % n); j = ice_src.index('End Asm', i)
    ice_levels.append([int(b, 2) for b in re.findall(r'([01]{8})b', ice_src[i:j])])
t = ice_src[ice_src.index('Dim iceLevelsTiles'):ice_src.index('Dim iceNPant')]
ice_tiles = [int(x) for x in re.findall(r'\d+', t[t.index('{'):])]
assert len(ice_tiles) == 40, len(ice_tiles)

gp = open(os.path.join(BAS, 'gfxParser.bas'), 'rb').read().decode('latin-1')
gp = gp[gp.index('gpPatterns:'):]
gp = gp[:gp.index('End Asm')]
patterns = [int(b, 2) for b in re.findall(r'^\s*defb ([01]{8})b', gp, re.M)]
assert len(patterns) == 64, len(patterns)

o = []
o.append('// Generated by tools_conv.py - do not edit\n')
o.append('#define SPR_FRAME_SIZE %d' % FRAME)
o.append('#define SPR_PLAYER 0\n#define SPR_ICE_TOP 12\n#define SPR_ICE_BOT 16\n')
o.append('extern unsigned char sprite_frames[];\nextern unsigned char charset[];\nextern unsigned char fill_patterns[];')
o.append('extern unsigned char ice_tiles[];\nextern unsigned char sky_apl[];')
for i in range(4):
    o.append('extern unsigned char ice_level_%d[];' % i)
for s in screens:
    o.append('extern unsigned char vec_%s[];' % s.replace('-', '_'))
conn = read_array(os.path.join(BAS, 'lhikoj.bas'), 'connections')
hots = read_array(os.path.join(BAS, 'lhikoj.bas'), 'hotspots')
assert len(conn) == 252 and len(hots) == 216
o.append('extern unsigned char connections[];\nextern unsigned char hotspots[];')
o.append('\n#asm')
o.append('._connections\n' + asm_bytes(conn, 7))
o.append('._hotspots\n' + asm_bytes(hots, 6))
o.append('._sprite_frames_pad\n' + asm_bytes(spr[:16]))
o.append('._sprite_frames\n' + asm_bytes(spr[16:]))
o.append('._charset\n' + asm_bytes(charset))
o.append('._fill_patterns\n' + asm_bytes(patterns, 8))
o.append('._ice_tiles\n' + asm_bytes(ice_tiles, 4))
for i, lv in enumerate(ice_levels):
    o.append('._ice_level_%d\n' % i + asm_bytes(lv))
for s in screens:
    d = list(open(os.path.join(GFX, s + '.bin'), 'rb').read()) + [1]   # RLE runs 1 short: pad
    o.append('._vec_%s\n' % s.replace('-', '_') + asm_bytes(d))
o.append('._sky_apl\n' + asm_bytes(list(open(os.path.join(GFX, 'c-scrollablesky.bin'), 'rb').read())))
o.append('#endasm\n')
open(os.path.join(HERE, 'src', 'assets.h'), 'w').write('\n'.join(o))

# preview of sprites + masks
try:
    from PIL import Image
    im = Image.new('RGB', (len(frames)*36, 18), (255, 0, 255))
    for i, c in enumerate(frames):
        g = sprite16(c); m = make_mask(g)
        for y in range(16):
            for x in range(16):
                gb = (g[y] >> (15-x)) & 1; mb = (m[y] >> (15-x)) & 1
                im.putpixel((i*36+x, y), (0, 0, 0) if gb else ((200, 220, 255) if mb else (255, 255, 255)))
    im.resize((im.width*3, im.height*3), Image.NEAREST).save(os.path.join(HERE, 'gfx', 'sprites_preview.png'))
except ImportError:
    pass
print('frames', len(frames), 'sprite bytes', len(spr))
